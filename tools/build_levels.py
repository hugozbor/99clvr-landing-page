#!/usr/bin/env python3
"""Rebuild levels.js from assets/levels/*.png.

The game reads each level's pixels to detect when the player leaves the path.
Browsers block that for image files opened straight from disk (file://), so the
level images are embedded in levels.js as data URIs instead.

Run this after editing any level PNG:  python3 tools/build_levels.py
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEVELS = ["LVL_1.png", "LVL2.png", "LVL3.png", "LVL4.png"]  # play order

lines = ["// Generated by tools/build_levels.py. Do not edit by hand.", "window.LEVELS = ["]
for name in LEVELS:
    data = base64.b64encode((ROOT / "assets" / "levels" / name).read_bytes()).decode()
    lines.append(f'  "data:image/png;base64,{data}",')
lines.append("];")

(ROOT / "levels.js").write_text("\n".join(lines) + "\n")
print(f"levels.js written ({len(LEVELS)} levels)")
